def readiness(as_is: str) -> str:
    """Готовность данных для измерения — выводится из состояния AS-IS.

    Методика прямо запрещает учитывать показатели без подтверждающих
    материалов и источника данных (п. 176), поэтому колонка показывает,
    можно ли вообще посчитать метрику сегодня.
    """
    low = as_is.lower()
    if low.startswith("вне периметра"):
        return "У владельца процесса"
    if low.startswith(("не исполняется", "не в дереве", "устарело")):
        return "Нет — учёт не ведётся"
    return "Частично — ручной учёт"


def short_owner(owner_dept: str) -> str:
    """Владелец на уровне подразделения — для развёрнутого реестра критериев.

    Полная должность занимает до четырёх строк и раздувает таблицу в сотни строк;
    она остаётся в карте ролей и на листе «Метрики по объектам».
    """
    return {
        "СТ (техническая служба)": "СТ",
        "Зерек (ИТ-инфраструктура)": "Зерек",
        "ДУП + ДРБ (разделено)": "ДУП и ДРБ",
        "ДУП + ОСУ (разделено)": "ДУП и ОСУ",
    }.get(owner_dept, owner_dept)


def objects():
    """Объекты процессной модели с ролью ДУП и владельцем одной строкой."""
    for p in PROCESSES:
        code, level, name = p[0], p[1], p[2]
        owner_dept, owner_role, detailed, as_is = p[6], p[7], p[8], p[14]
        yield {
            "code": code,
            "level": level,
            "name": name,
            "owner": owner_text(detailed, owner_dept, owner_role),
            "owner_short": short_owner(owner_dept),
            "role": simple_role(code, detailed, owner_dept),
            "contribution": p[10].rstrip(" ."),
            "as_is": as_is,
            "readiness": readiness(as_is),
        }


def criteria_rows():
    """Развёрнутый реестр: одна строка — один критерий оценки одного объекта."""
    rows = []
    for obj in objects():
        role, level = obj["role"], obj["level"]
        head = (obj["code"], level, obj["name"], obj["owner_short"], role)
        tail = (SCOPE[role], METRIC_ROLE[role], obj["readiness"])

        if obj["code"] in SPECIFIC:
            group, kpi_name, formula, target = SPECIFIC[obj["code"]]
            rows.append(head + (
                group, f"KPI объекта: {kpi_name}", formula, target,
                "Паспорт процесса (Приложение №2 Методики)", FREQ_DEFAULT,
            ) + tail)

        for key in PROFILES[(role, level)]:
            name, group, _purpose, formula, _unit, target, _chapter = METRICS[key]
            if role == КЛИЕНТ and key in CLIENT_WORDING:
                name = f"{name} — {CLIENT_WORDING[key]}"
            rows.append(head + (
                group, name, formula, target,
                SOURCES[key], FREQ.get(key, FREQ_DEFAULT),
            ) + tail)
    return rows


