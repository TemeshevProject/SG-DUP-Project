def build_maturity(wb):
    ws = wb.create_sheet("Оценка зрелости")
    ws["A1"] = "Базовая оценка зрелости сквозных процессов ДУП (Глава 15 Методики)"
    ws["A1"].font = Font(bold=True, size=14, color="1F3864")
    ws["A2"] = (
        "Оценка проводится ежеквартально по семи критериям. Процесс соответствует уровню "
        "по критерию только при выполнении всех требований уровня и наличии подтверждающих "
        "материалов (п. 178). Итоговый уровень процесса равен наименьшему подтверждённому "
        "среди семи критериев; среднее арифметическое не применяется (п. 179). "
        f"Целевой уровень для процессов ДУП — «{MATURITY_TARGET}». "
        "Фазы соответствуют дорожной карте проекта трансформации ДУП."
    )
    ws.merge_cells("A2:F2")
    ws["A2"].alignment = Alignment(wrap_text=True, vertical="top")
    ws.row_dimensions[2].height = 60

    rows = [(p, c, lvl, why, todo, MATURITY_TARGET, phase)
            for p, c, lvl, why, todo, phase in MATURITY]
    headers = ["Процесс", "Критерий зрелости", "Текущий уровень",
               "Обоснование оценки", "Что нужно для целевого уровня",
               "Целевой уровень", "Фаза дорожной карты"]
    write_table(ws, headers, rows, start=4,
                widths=[36, 30, 17, 62, 58, 17, 18])

    prev = None
    for i, row in enumerate(rows):
        r = 5 + i
        if row[0] != prev:
            ws.cell(row=r, column=1).font = Font(bold=True, size=10)
            prev = row[0]
        else:
            ws.cell(row=r, column=1).value = None
        ws.cell(row=r, column=3).fill = PatternFill("solid", fgColor="F8CBC4")

    итог = (
        "Итоговый уровень зрелости каждого из пяти сквозных процессов ДУП — 1 (Начальный): "
        "ни по одному критерию не выполнены требования второго уровня, поскольку паспорта "
        "процессов не оформлены, а фактические значения метрик не измеряются. "
        "Единственный владелец закреплён за каждым объектом, поэтому первый шаг к уровню 2 "
        "одинаков для всех процессов — утвердить паспорт процесса с картой SIPOC и начать "
        "измерять фактические значения."
    )
    r = 5 + len(rows) + 1
    ws.cell(row=r, column=1, value=итог)
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=7)
    ws.cell(row=r, column=1).alignment = Alignment(wrap_text=True, vertical="top")
    ws.cell(row=r, column=1).font = Font(bold=True, size=10)
    ws.row_dimensions[r].height = 60

    ws.freeze_panes = "A5"
    setup_print(ws, title_rows="4:4")
    return ws


def main() -> None:
    wb = Workbook()
    wb.remove(wb.active)

    all_objects = list(objects())
    counts = Counter(o["role"] for o in all_objects)

    build_guide(wb, counts)
    rows = criteria_rows()
    build_criteria(wb, rows)
    build_summary(wb)
    build_catalog(wb)
    build_passport(wb)
    build_maturity(wb)

    wb.save(OUTPUT)

    print(f"Сохранено: {OUTPUT}")
    print(f"Объектов: {len(all_objects)} | критериев оценки: {len(rows)}")
    for role in ROLE_ORDER:
        n = counts.get(role, 0)
        k = sum(1 for r in rows if r[4] == role)
        print(f"  {role}: объектов {n}, критериев {k}")
    by_group = Counter(r[5] for r in rows)
    print("  По группам: " + ", ".join(f"{g} — {by_group[g]}" for g in GROUP_ORDER))


if __name__ == "__main__":
    main()
