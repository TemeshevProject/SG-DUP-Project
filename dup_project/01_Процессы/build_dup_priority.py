def build_matrix(wb, rows):
    ws = wb.create_sheet("Матрица ценность — лёгкость")
    ws["A1"] = "Матрица «ценность — лёгкость реализации»"
    ws["A1"].font = BIG_TITLE_FONT
    ws.merge_cells("A2:G2")
    ws["A2"] = (
        "Ценность — взвешенная сумма четырёх критериев без учёта лёгкости: влияние "
        "на результат, экономия времени, экономия денег и риск бездействия. Граница между "
        "высокой и умеренной ценностью проходит по 60 баллам из 100, граница лёгкости — "
        "по оценке 4 из 5. Матрица не заменяет очередь работ: она объясняет, почему объект "
        "в неё попал."
    )
    ws["A2"].alignment = WRAP
    ws.row_dimensions[2].height = 45

    scored = [r for r in rows if r["total"] is not None]
    quad_fill = {
        QUADRANTS[0][0]: PatternFill("solid", fgColor="C6E9D5"),
        QUADRANTS[1][0]: PatternFill("solid", fgColor="FFF2CC"),
        QUADRANTS[2][0]: PatternFill("solid", fgColor="E2EFDA"),
        QUADRANTS[3][0]: PatternFill("solid", fgColor="EDEDED"),
    }
    # Квадранты занимают по несколько столбцов: ширины листа заданы нижней
    # таблицей объектов, и в один столбец список кодов не помещается.
    SPANS = [(1, 2), (3, 5), (6, 7)]

    layout = [
        ("Ценность высокая (≥ 60)", QUADRANTS[0][0], QUADRANTS[1][0]),
        ("Ценность умеренная (< 60)", QUADRANTS[2][0], QUADRANTS[3][0]),
    ]
    grid = []
    for label, left, right in layout:
        cells = [label]
        for name in (left, right):
            codes = [o["code"] for o in scored if o["quadrant"] == name]
            cells.append(f"{name} — {len(codes)}\n" + ", ".join(codes))
        grid.append(tuple(cells))
    grid_top = 5
    end = write_spanned_table(
        ws, ["", "Реализация лёгкая (4–5 из 5)", "Реализация тяжёлая (1–3 из 5)"],
        grid, SPANS, start=grid_top,
    )
    for i, (label, left, right) in enumerate(layout):
        r = grid_top + 1 + i
        cell = ws.cell(row=r, column=1)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        for c, name in zip((3, 6), (left, right)):
            ws.cell(row=r, column=c).fill = quad_fill[name]
        ws.row_dimensions[r].height = 80

    ws.cell(row=end + 2, column=1, value="Что делать с каждым квадрантом").font = TITLE_FONT
    end = write_spanned_table(
        ws, ["Квадрант", "Определение", "Управленческое решение"],
        QUADRANTS, SPANS, start=end + 3,
    )
    for i, quad in enumerate(QUADRANTS):
        ws.cell(row=end - len(QUADRANTS) + 1 + i, column=1).fill = quad_fill[quad[0]]

    ws.cell(row=end + 2, column=1, value="Объекты в координатах матрицы").font = TITLE_FONT
    detail = [
        (o["code"], o["name"], o["value"], o["scores"][-1], o["quadrant"],
         o["wave"], o["total"])
        for o in sorted(scored, key=lambda o: (-o["value"], -o["scores"][-1]))
    ]
    end = write_table(
        ws,
        ["Код", "Наименование объекта", "Ценность (0–100)", "Лёгкость (1–5)",
         "Квадрант", "Волна", "Итоговый балл"],
        detail, start=end + 3, widths=[10, 46, 14, 14, 24, 30, 14],
    )
    first_detail = end - len(detail) + 1
    for i, row in enumerate(detail):
        r = first_detail + i
        for c in (3, 4, 7):
            ws.cell(row=r, column=c).alignment = CENTER
        ws.cell(row=r, column=5).fill = quad_fill[row[4]]
        ws.cell(row=r, column=6).fill = WAVE_FILLS[row[5]]
    setup_print(ws, title_rows=None)


def main() -> None:
    codes = [p[0] for p in PROCESSES]
    missing = [c for c in codes if c not in PRIORITY]
    extra = [c for c in PRIORITY if c not in codes]
    if missing or extra:
        raise SystemExit(f"Реестр и приоритеты разошлись: нет оценок {missing}, лишние {extra}")
    for code, data in PRIORITY.items():
        scores = data[:5]
        if scores[0] is not None and not all(isinstance(s, int) and 1 <= s <= 5 for s in scores):
            raise SystemExit(f"Оценка вне шкалы 1–5: {code} → {scores}")
        unknown = [k for k in data[10] if k not in METRICS]
        if unknown:
            raise SystemExit(f"Метрика вне справочника: {code} → {unknown}")
    preds = {c.strip() for data in PRIORITY.values() for c in data[8].split(",")}
    unknown_preds = preds - set(codes) - {"—", ""}
    if unknown_preds:
        raise SystemExit(f"Предшественник вне реестра: {unknown_preds}")
    # Очередь обязана читаться сверху вниз: предшественник не может ждать своей волны
    # позже, чем объект, который от него зависит.
    late = [
        f"{code} ({WAVE_ORDER.index(data[5])}) ← {pred} ({WAVE_ORDER.index(PRIORITY[pred][5])})"
        for code, data in PRIORITY.items()
        for pred in (c.strip() for c in data[8].split(","))
        if pred in PRIORITY and WAVE_ORDER.index(PRIORITY[pred][5]) > WAVE_ORDER.index(data[5])
    ]
    if late:
        raise SystemExit(f"Предшественник стоит в более поздней волне: {late}")

    rows = objects()

    wb = Workbook()
    wb.remove(wb.active)
    build_guide(wb, rows)
    build_priority(wb, rows)
    build_sequence(wb, rows)
    build_first_steps(wb)
    build_matrix(wb, rows)
    wb.save(OUTPUT)

    scored = [r for r in rows if r["total"] is not None]
    by_wave = Counter(r["wave"] for r in rows)
    by_quadrant = Counter(r["quadrant"] for r in scored)
    print(f"Сохранено: {OUTPUT}")
    print(f"Объектов: {len(rows)} | оценено: {len(scored)}")
    for wave in WAVE_ORDER:
        if by_wave.get(wave):
            print(f"  {wave}: {by_wave[wave]}")
    print("  Квадранты: " + ", ".join(f"{q[0]} — {by_quadrant.get(q[0], 0)}" for q in QUADRANTS))
    print("  Первые пять в очереди: "
          + ", ".join(f"{r['code']} ({r['total']})" for r in rows[:5]))


if __name__ == "__main__":
    main()
