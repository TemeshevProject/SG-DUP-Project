"""Приоритеты реинжиниринга процессов ДУП: чем занимаемся первым и почему.

Файл отвечает на вопрос «с чего начинать». Каждый процесс, подпроцесс и этап
из реестра получает оценку по пяти критериям, итоговый балл и место в очереди
работ, а к нему — письменное обоснование, почему объект берётся именно тогда.

Данные об объектах берутся из карты ролей (build_dup_role_map.py), роль ДУП —
из краткой карты (build_dup_role_map_simple.py), названия подтверждающих
метрик — из реестра критериев оценки (build_dup_metrics.py). Ни одно значение
не дублируется вручную, поэтому четыре файла не могут разойтись между собой.

Модель приоритизации опирается на Методику KT_METHOD:

  * п. 195 — перечень оснований, при которых бизнес-владелец обязан
    инициировать анализ и пересмотр процесса. Пять критериев оценки собраны
    так, чтобы каждое основание попало хотя бы в один критерий.
  * Таблица 20, этап 4 «Улучшение» — приоритизация улучшений названа
    отдельным этапом цикла управления, то есть обязательной процедурой.
  * п. 140 — до устранения шага-ограничителя оптимизация остальных шагов не
    приводит к сокращению общего времени. Отсюда правило: узкое место берётся
    раньше соседних шагов, даже если его балл ниже.
  * п. 33 — пока не закреплена единственная роль A, за результат не отвечает
    никто и метрики установить нельзя. Отсюда правило волны 1: объекты без
    владельца выходят в работу первыми независимо от балла.

Очередь работ строится в два прохода. Сначала объект попадает в волну —
это управленческое решение, учитывающее зависимости: нельзя оптимизировать
то, у чего нет владельца, и нельзя доказать эффект, пока не снята базовая
линия. Внутри волны объекты идут по убыванию балла. Сортировка листа
«Приоритеты» по колонке «Итоговый балл» даёт чистый рейтинг ценности без
учёта зависимостей.
"""

