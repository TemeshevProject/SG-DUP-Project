def metric_label(key: str) -> str:
    """Короткое имя метрики: до пояснения через тире или скобку."""
    name = METRICS[key][0]
    for sep in (" — ", " ("):
        if sep in name:
            return name.split(sep)[0]
    return name


def total_score(scores) -> float | None:
    """Взвешенный балл, приведённый к шкале 0–100."""
    if scores[0] is None:
        return None
    raw = sum(s * WEIGHTS[k] for s, k in zip(scores, CRIT_KEYS))
    return round(raw / MAX_SCORE * 100, 1)


def value_score(scores) -> float | None:
    """Ценность без учёта лёгкости — ось Y матрицы «ценность / лёгкость»."""
    if scores[0] is None:
        return None
    keys = CRIT_KEYS[:-1]
    raw = sum(s * WEIGHTS[k] for s, k in zip(scores[:-1], keys))
    return round(raw / (sum(WEIGHTS[k] for k in keys) * 5) * 100, 1)


def quadrant(scores) -> str | None:
    if scores[0] is None:
        return None
    high_value = value_score(scores) >= 60
    easy = scores[-1] >= 4
    if high_value:
        return QUADRANTS[0][0] if easy else QUADRANTS[1][0]
    return QUADRANTS[2][0] if easy else QUADRANTS[3][0]


def order_within_wave(rows):
    """Порядок внутри волны: по убыванию балла, но не раньше своих предшественников.

    Сортировки по одному баллу недостаточно: объект с более высоким баллом может
    зависеть от соседа по волне, и тогда очередь читается как противоречие сама
    себе. Зависимости за пределами волны здесь не учитываются — их разводят волны.
    """
    pending = {r["code"]: r for r in rows}
    deps = {code: {c.strip() for c in r["pred"].split(",")} & set(pending)
            for code, r in pending.items()}
    ordered, done = [], set()
    while pending:
        ready = [c for c in pending if not deps[c] - done]
        if not ready:  # взаимная зависимость внутри волны — разрываем по баллу
            ready = list(pending)
        code = min(ready, key=lambda c: (-(pending[c]["total"] or 0), c))
        ordered.append(pending.pop(code))
        done.add(code)
    return ordered


def objects():
    """Объекты реестра с ролью ДУП, оценками и обоснованием, в порядке очереди."""
    rows = []
    for p in PROCESSES:
        code, level, name = p[0], p[1], p[2]
        owner_dept, dup_role = p[6], p[8]
        scores = PRIORITY[code][:5]
        wave, kind, first, pred, why, keys = PRIORITY[code][5:]
        rows.append({
            "code": code,
            "level": level,
            "name": name,
            "owner": short_owner(owner_dept),
            "role": simple_role(code, dup_role, owner_dept),
            "scores": scores,
            "total": total_score(scores),
            "value": value_score(scores),
            "quadrant": quadrant(scores),
            "wave": wave,
            "kind": kind,
            "first": first,
            "pred": pred,
            "why": why,
            "proof": "; ".join(metric_label(k) for k in keys) or "—",
        })
    # Очередь: сначала волна, внутри волны — убывание балла с учётом предшественников.
    queue = []
    for wave in WAVE_ORDER:
        queue.extend(order_within_wave([r for r in rows if r["wave"] == wave]))
    for i, row in enumerate(queue, 1):
        row["rank"] = i if row["wave"] != АГ else None
    return queue


