def metric_label(key: str) -> str:
    """Короткое имя метрики: до пояснения через тире или скобку."""
    name = METRICS[key][0]
    for sep in (" — ", " ("):
        if sep in name:
            return name.split(sep)[0]
    return name


def total_score(scores) -> float | None:
    """Взвешенный балл, приведённый к шкале 0–100."""
    if scores[0] is None:
        return None
    raw = sum(s * WEIGHTS[k] for s, k in zip(scores, CRIT_KEYS))
    return round(raw / MAX_SCORE * 100, 1)


def value_score(scores) -> float | None:
    """Ценность без учёта лёгкости — ось Y матрицы «ценность / лёгкость»."""
    if scores[0] is None:
        return None
    keys = CRIT_KEYS[:-1]
    raw = sum(s * WEIGHTS[k] for s, k in zip(scores[:-1], keys))
    return round(raw / (sum(WEIGHTS[k] for k in keys) * 5) * 100, 1)


