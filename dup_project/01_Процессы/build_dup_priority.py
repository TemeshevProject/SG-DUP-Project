def main() -> None:
    codes = [p[0] for p in PROCESSES]
    missing = [c for c in codes if c not in PRIORITY]
    extra = [c for c in PRIORITY if c not in codes]
    if missing or extra:
        raise SystemExit(f"Реестр и приоритеты разошлись: нет оценок {missing}, лишние {extra}")
    for code, data in PRIORITY.items():
        scores = data[:5]
        if scores[0] is not None and not all(isinstance(s, int) and 1 <= s <= 5 for s in scores):
            raise SystemExit(f"Оценка вне шкалы 1–5: {code} → {scores}")
        unknown = [k for k in data[10] if k not in METRICS]
        if unknown:
            raise SystemExit(f"Метрика вне справочника: {code} → {unknown}")
    preds = {c.strip() for data in PRIORITY.values() for c in data[8].split(",")}
    unknown_preds = preds - set(codes) - {"—", ""}
    if unknown_preds:
        raise SystemExit(f"Предшественник вне реестра: {unknown_preds}")

    rows = objects()

    wb = Workbook()
    wb.remove(wb.active)
    build_guide(wb, rows)
    build_priority(wb, rows)
    build_sequence(wb, rows)
    build_first_steps(wb)
    build_matrix(wb, rows)
    wb.save(OUTPUT)

    scored = [r for r in rows if r["total"] is not None]
    by_wave = Counter(r["wave"] for r in rows)
    by_quadrant = Counter(r["quadrant"] for r in scored)
    print(f"Сохранено: {OUTPUT}")
    print(f"Объектов: {len(rows)} | оценено: {len(scored)}")
    for wave in WAVE_ORDER:
        if by_wave.get(wave):
            print(f"  {wave}: {by_wave[wave]}")
    print("  Квадранты: " + ", ".join(f"{q[0]} — {by_quadrant.get(q[0], 0)}" for q in QUADRANTS))
    print("  Первые пять в очереди: "
          + ", ".join(f"{r['code']} ({r['total']})" for r in rows[:5]))


