def style_header(ws, row, count):
    for c in range(1, count + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER


def write_table(ws, headers, rows, start=1, widths=None):
    for c, h in enumerate(headers, 1):
        ws.cell(row=start, column=c, value=h)
    style_header(ws, start, len(headers))
    for r, values in enumerate(rows, start + 1):
        for c, val in enumerate(values, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.border = BORDER
            cell.alignment = WRAP
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    return start + len(rows)


def write_spanned_table(ws, headers, rows, spans, start=1):
    """Таблица, каждая колонка которой занимает несколько столбцов листа.

    Ширина столбца в Excel общая для всего листа, поэтому узкие столбцы широкой
    таблицы ломают вёрстку узкой таблицы, стоящей ниже на том же листе. Здесь
    колонка растягивается на нужный диапазон вместо того, чтобы подстраиваться
    под чужую ширину.
    """
    ncols = spans[-1][1]
    for (c1, c2), header in zip(spans, headers):
        ws.cell(row=start, column=c1, value=header)
        if c2 > c1:
            ws.merge_cells(start_row=start, start_column=c1, end_row=start, end_column=c2)
    style_header(ws, start, ncols)
    for r, values in enumerate(rows, start + 1):
        for (c1, c2), val in zip(spans, values):
            ws.cell(row=r, column=c1, value=val)
            if c2 > c1:
                ws.merge_cells(start_row=r, start_column=c1, end_row=r, end_column=c2)
        for c in range(1, ncols + 1):
            ws.cell(row=r, column=c).border = BORDER
            ws.cell(row=r, column=c).alignment = WRAP
    return start + len(rows)


