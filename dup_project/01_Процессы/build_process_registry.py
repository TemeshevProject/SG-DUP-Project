def style_header(ws, row: int, ncol: int) -> None:
    for c in range(1, ncol + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER


def build_registry_sheet(wb: Workbook) -> None:
    ws = wb.active
    ws.title = "Реестр процессов"
    headers = [
        "Код", "Уровень", "Наименование", "Родитель", "Блок", "Слой",
        "Бизнес-владелец (A)", "Исполнитель (R)", "Консультант (C)", "Информируемый (I)",
        "Внешние интерфейсы", "Статус AS-IS", "Приоритет", "Тип работ",
        "Нормативная база", "Узкое место №", "Комментарий",
    ]
    for i, h in enumerate(headers, 1):
        ws.cell(row=1, column=i, value=h)
    style_header(ws, 1, len(headers))

    for r, row in enumerate(PROCESSES, 2):
        block_key = row[4][0] if row[4] else "Ж"
        fill = BLOCK_FILLS.get(block_key, BLOCK_FILLS["ЖЦ"])
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.alignment = WRAP
            cell.border = BORDER
            if c <= 5:
                cell.fill = fill

    widths = [8, 12, 42, 10, 18, 6, 22, 18, 18, 14, 22, 16, 8, 14, 20, 10, 30]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"


