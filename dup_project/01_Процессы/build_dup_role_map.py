def setup_print(ws, *, header_row: int | None = None) -> None:
    """Альбомная ориентация, вписывание по ширине и сквозная шапка при печати."""
    ws.page_setup.orientation = "landscape"
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    if header_row:
        ws.print_title_rows = f"{header_row}:{header_row}"


def style_header(ws, row: int, ncol: int) -> None:
    for c in range(1, ncol + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER


def write_table(ws, headers, widths, rows, *, start_row=1, role_col=None, block_col=None,
                set_widths=True):
    for i, h in enumerate(headers, 1):
        ws.cell(row=start_row, column=i, value=h)
    style_header(ws, start_row, len(headers))
    for r, row in enumerate(rows, start_row + 1):
        for c, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.alignment = WRAP
            cell.border = BORDER
        if role_col:
            role_cell = ws.cell(row=r, column=role_col)
            fill = ROLE_FILLS.get(role_cell.value)
            if fill:
                role_cell.fill = fill
                role_cell.font = BOLD
        if block_col:
            block_val = ws.cell(row=r, column=block_col).value or ""
            fill = BLOCK_FILLS.get(block_val[:1])
            if fill:
                for c in range(1, 6):
                    ws.cell(row=r, column=c).fill = fill
    if set_widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    return start_row + len(rows)


