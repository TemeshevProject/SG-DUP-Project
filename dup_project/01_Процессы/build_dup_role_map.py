def build_summary(wb: Workbook) -> None:
    ws = wb.create_sheet("Сводка")
    ws["A1"] = "Сводка по ролям ДУП"
    ws["A1"].font = Font(bold=True, size=14, color="1F3864")

    total = len(PROCESSES)
    by_role = Counter(p[8] for p in PROCESSES)
    rows = [
        (role, by_role.get(role, 0), f"{by_role.get(role, 0) / total:.0%}")
        for role in ROLE_ORDER
    ]
    rows.append(("ИТОГО", total, "100%"))
    ws["A3"] = "Распределение записей по роли ДУП"
    ws["A3"].font = TITLE_FONT
    last = write_table(ws, ["Роль ДУП", "Записей", "Доля"], [], rows, start_row=4,
                       role_col=1, set_widths=False)

    blocks = list(OrderedDict.fromkeys(p[4] for p in PROCESSES))
    cross_headers = ["Блок ДУП"] + ROLE_ORDER + ["Всего"]
    cross_rows = []
    for b in blocks:
        recs = [p for p in PROCESSES if p[4] == b]
        counts = Counter(p[8] for p in recs)
        cross_rows.append([b] + [counts.get(r, 0) or "" for r in ROLE_ORDER] + [len(recs)])
    ws.cell(row=last + 2, column=1, value="Роли ДУП в разрезе блоков").font = TITLE_FONT
    last = write_table(ws, cross_headers, [], cross_rows, start_row=last + 3, set_widths=False)

    owners = Counter(p[6] for p in PROCESSES)
    owner_rows = []
    for owner, cnt in sorted(owners.items(), key=lambda kv: (-kv[1], kv[0])):
        codes = ", ".join(p[0] for p in PROCESSES if p[6] == owner)
        owner_rows.append((owner, cnt, codes))
    ws.cell(row=last + 2, column=1, value="Кто является генеральным владельцем процесса").font = TITLE_FONT
    owners_start = last + 3
    last = write_table(ws, ["Подразделение-владелец", "Записей", "Коды процессов"], [],
                       owner_rows, start_row=owners_start, set_widths=False)
    # Список кодов длинный — растягиваем его на свободные колонки таблицы выше.
    for r in range(owners_start, last + 1):
        ws.merge_cells(start_row=r, start_column=3, end_row=r, end_column=len(cross_headers))

    for i, w in enumerate((36, 15, 17, 17, 17, 17, 13, 11), 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    setup_print(ws)


