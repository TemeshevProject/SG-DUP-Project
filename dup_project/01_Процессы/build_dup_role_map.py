def main() -> None:
    unknown = {p[8] for p in PROCESSES} - set(ROLE_ORDER)
    if unknown:
        raise SystemExit(f"Неизвестные значения роли ДУП: {unknown}")
    unknown_owners = {p[6] for p in PROCESSES} - OWNER_DEPTS
    if unknown_owners:
        raise SystemExit(f"Владелец вне справочника подразделений: {unknown_owners}")
    bad = [p[0] for p in PROCESSES if len(p) != len(HEADERS)]
    if bad:
        raise SystemExit(f"Число колонок не совпадает с заголовками: {bad}")
    ownerless = [p[0] for p in PROCESSES if p[8] == НЗ]
    if ownerless:
        raise SystemExit(f"Объекты без владельца — назначение обязательно: {ownerless}")
    codes = {p[0] for p in PROCESSES}
    missing = [c for c, *_ in OWNER_DECISIONS if c not in codes]
    if missing:
        raise SystemExit(f"Решение о владельце ссылается на несуществующий код: {missing}")
    decided = {c for c, *_ in OWNER_DECISIONS}
    no_decision = [c for c in DECISIONS_AWAITING_DOCUMENT if c not in decided]
    if no_decision:
        raise SystemExit(f"Ждёт документа решение, которого нет в протоколе: {no_decision}")

    wb = Workbook()
    build_legend(wb)
    build_map(wb)
    build_slice(
        wb, "ДУП — генеральный владелец", {ГВ},
        "Процессы, за результат которых отвечает ДУП. Инструмент управления — приказ, "
        "регламент и KPI внутри департамента.",
    )
    build_slice(
        wb, "ДУП — участник", {УИ, УД, ИНФ, СВ},
        "Процессы, которыми владеют другие подразделения или где ответственность разделена. "
        "Инструмент управления — согласованный SLA на стык: состав данных, срок и ответственный с обеих сторон.",
    )
    build_owner_decisions(wb)
    build_summary(wb)
    build_findings(wb)
    build_interfaces(wb)
    wb.save(OUTPUT)

    by_role = Counter(p[8] for p in PROCESSES)
    print(f"Сохранено: {OUTPUT}")
    print(f"Записей: {len(PROCESSES)}")
    for role in ROLE_ORDER:
        print(f"  {role}: {by_role.get(role, 0)}")


if __name__ == "__main__":
    main()
