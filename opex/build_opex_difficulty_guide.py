def read_source():
    """Группы, рычаги и количество позиций из исходной книги артефактов."""
    ws = load_workbook(SOURCE)["Все артефакты"]
    records = [
        (ws.cell(r, 1).value, ws.cell(r, 2).value, ws.cell(r, 6).value, ws.cell(r, 7).value)
        for r in range(2, ws.max_row + 1)
    ]
    groups = OrderedDict()
    for kind, group, difficulty, lever in records:
        entry = groups.setdefault(group, {"difficulty": difficulty, "lever": lever,
                                          "total": 0, "CAPEX": 0, "OPEX": 0})
        if entry["difficulty"] != difficulty:
            raise SystemExit(f"Внутри группы «{group}» сложность различается — "
                             "оценка перестала быть групповой")
        entry["total"] += 1
        entry[kind] += 1
    return records, groups


def check_siblings(groups):
    """Отображение группа → сложность должно совпадать во всех версиях книги."""
    base = {g: d["difficulty"] for g, d in groups.items()}
    for path in SIBLINGS:
        if not path.exists():
            continue
        ws = load_workbook(path)["Все артефакты"]
        other = {ws.cell(r, 2).value: ws.cell(r, 6).value for r in range(2, ws.max_row + 1)}
        if other != base:
            diff = {g for g in set(base) | set(other) if base.get(g) != other.get(g)}
            raise SystemExit(f"Версия {path.name} даёт другую сложность по группам: {diff}")
    return len([p for p in SIBLINGS if p.exists()]) + 1


def level_of(difficulty: str) -> int:
    return int(str(difficulty).split(" ")[0])


def style_header(ws, row, count):
    for c in range(1, count + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER


def write_table(ws, headers, rows, start=1, widths=None):
    for c, h in enumerate(headers, 1):
        ws.cell(row=start, column=c, value=h)
    style_header(ws, start, len(headers))
    for r, values in enumerate(rows, start + 1):
        for c, val in enumerate(values, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.border = BORDER
            cell.alignment = WRAP
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    return start + len(rows)


